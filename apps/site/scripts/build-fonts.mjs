// Writes src/styles/fonts.css: self-hosted @font-face rules for the landing page, woff2 only.
//   - Inter Variable: latin + latin-ext (the page never needs Cyrillic, Greek or Vietnamese)
//   - JetBrains Mono Variable: latin (timecodes, commands)
//   - Noto Sans SC 700: every slice (headings, one weight; browsers fetch only the slices a page uses)
// Fontsource's own CSS lists woff as well as woff2, and the bundler would copy both; only woff2 is kept.
// Run after upgrading a @fontsource package: node scripts/build-fonts.mjs, and commit the result.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { format } from 'prettier'

const here = path.dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const out = path.join(here, '../src/styles/fonts.css')

function pkg(name) {
  const json = require.resolve(`${name}/package.json`)
  return { dir: path.dirname(json), version: JSON.parse(readFileSync(json, 'utf8')).version }
}

/** @font-face blocks of a fontsource css file as { comment, body }. */
function blocks(file) {
  const text = readFileSync(file, 'utf8')
  return [...text.matchAll(/\/\*\s*([^*]+?)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)].map((m) => ({
    name: m[1],
    css: m[2],
  }))
}

/** Keep only the woff2 source and point it at node_modules/<pkg>/files relative to the output. */
function woff2Only(css, pkgName) {
  const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(css)?.[1]
  if (!file) throw new Error(`no woff2 in: ${css}`)
  const format = /format\('(woff2[^']*)'\)/.exec(css)?.[1] ?? 'woff2'
  const rel = `../../node_modules/${pkgName}/files/${file}`
  return css.replace(/src:[^;]*;/, `src: url(${rel}) format('${format}');`)
}

const parts = []
const versions = []

const inter = pkg('@fontsource-variable/inter')
versions.push(`inter ${inter.version}`)
for (const b of blocks(path.join(inter.dir, 'wght.css'))) {
  if (/^inter-(latin|latin-ext)-wght-normal$/.test(b.name))
    parts.push(woff2Only(b.css, '@fontsource-variable/inter'))
}

const mono = pkg('@fontsource-variable/jetbrains-mono')
versions.push(`jetbrains-mono ${mono.version}`)
for (const b of blocks(path.join(mono.dir, 'wght.css'))) {
  if (b.name === 'jetbrains-mono-latin-wght-normal')
    parts.push(woff2Only(b.css, '@fontsource-variable/jetbrains-mono'))
}

const noto = pkg('@fontsource/noto-sans-sc')
versions.push(`noto-sans-sc ${noto.version}`)
const notoBlocks = blocks(path.join(noto.dir, '700.css'))
if (notoBlocks.length < 90)
  throw new Error(`expected ~101 Noto Sans SC slices, got ${notoBlocks.length}`)
for (const b of notoBlocks) parts.push(woff2Only(b.css, '@fontsource/noto-sans-sc'))

const header = `/*
 * Generated by scripts/build-fonts.mjs, do not edit by hand.
 * Sources: ${versions.join(', ')} (all OFL-1.1). Self-hosted, woff2 only; the page never contacts a font server.
 */
`
// Formatted the way `pnpm format:check` expects, so regenerating never leaves a diff behind.
writeFileSync(
  out,
  await format(header + parts.join('\n\n') + '\n', {
    parser: 'css',
    singleQuote: true,
    printWidth: 100,
  }),
)
console.log(`wrote ${path.relative(process.cwd(), out)} (${parts.length} faces)`)
