export const GLYPH_W = 5
export const GLYPH_H = 7

const rows = new Map<string, string[]>()
for (const [ch, def] of Object.entries(G)) rows.set(ch, def.split('|'))

/** 一个字符的点阵（缺省字符画成空格）。 */
export function glyph(ch: string): string[] {
  return rows.get(ch) ?? rows.get(ch.toUpperCase()) ?? rows.get(' ')!
}

/** 文本宽度（像素，scale 倍放大，字间距 1 个点）。 */
export function textWidth(text: string, scale: number): number {
  return text.length === 0 ? 0 : (text.length * (GLYPH_W + 1) - 1) * scale
}
